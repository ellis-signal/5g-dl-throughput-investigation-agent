#!/usr/bin/env python3
"""Embed the generated ledger into the frontend for offline (file://) fallback.

The web page prefers the live API; this bundle only exists so the demo also
works when opened straight from disk. Regenerate after changing data or rules.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent


def main(argv):
    source = Path(argv[1]) if len(argv) > 1 else ROOT / 'out' / 'ledger.json'
    ledger = json.loads(source.read_text(encoding='utf-8'))
    target = ROOT / 'frontend' / 'ledger-data.js'
    payload = json.dumps(ledger, ensure_ascii=False, separators=(',', ':'))
    target.write_text(
        '/* generated by tools/embed_ledger.py — do not edit by hand */\n'
        f'window.EMBEDDED_LEDGER = {payload};\n',
        encoding='utf-8',
    )
    print(f'embedded {len(ledger["cells"])} cells -> {target} ({target.stat().st_size} bytes)')


if __name__ == '__main__':
    main(sys.argv)